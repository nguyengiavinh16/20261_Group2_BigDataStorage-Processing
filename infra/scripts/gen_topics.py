"""Generate Strimzi KafkaTopic CRs from contracts/kafka-topics.yaml.

python infra/scripts/gen_topics.py --profile local --out infra/k8s/generated/topics.local.yaml
"""

import argparse
import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
REGISTRY = ROOT / "contracts" / "kafka-topics.yaml"


def k8s_name(topic: str) -> str:
    """KafkaTopic metadata.name must be an RFC 1123 subdomain: no underscores."""
    return re.sub(r"[^a-z0-9.-]", "-", topic.lower())


def build(profile: str) -> list[dict]:
    registry = yaml.safe_load(REGISTRY.read_text(encoding="utf-8"))
    defaults = registry["defaults"][profile]
    base_config = dict(registry["defaults"].get("config", {}))
    if profile == "cloud":
        base_config["min.insync.replicas"] = 2

    docs = []
    for t in registry["topics"]:
        config = {**base_config, "retention.ms": int(t["retention_hours"]) * 3_600_000}
        docs.append(
            {
                "apiVersion": "kafka.strimzi.io/v1beta2",
                "kind": "KafkaTopic",
                "metadata": {
                    "name": k8s_name(t["name"]),
                    "namespace": "cg-kafka",
                    "labels": {
                        "strimzi.io/cluster": "cg-kafka",
                        "app.kubernetes.io/part-of": "cryptoguard",
                    },
                },
                "spec": {
                    "topicName": t["name"],
                    "partitions": int(t.get("partitions", defaults["partitions"])),
                    "replicas": int(defaults["replicas"]),
                    "config": config,
                },
            }
        )
    return docs


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--profile", choices=["local", "cloud"], required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args()

    docs = build(args.profile)
    out = ROOT / args.out
    out.parent.mkdir(parents=True, exist_ok=True)
    header = "# GENERATED by infra/scripts/gen_topics.py from contracts/kafka-topics.yaml. Do not edit.\n"
    out.write_text(
        header + yaml.safe_dump_all(docs, sort_keys=False), encoding="utf-8", newline="\n"
    )
    print(f"wrote {len(docs)} topics to {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
